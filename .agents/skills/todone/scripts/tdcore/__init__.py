"""Ядро системы очередей задач: классы по ответственностям.

Состав пакета:
- `schema` — схемы данными: ключи, перечисления, регулярки, пороги настройки;
- `errors` — находка, отказ, коды возврата, таблица готовых действий;
- `record` — запись задачи и первый уровень валидации: схема и факты;
- `store` — папка записей: чтение, атомарная запись, следующий идентификатор;
- `index` — индекс очереди: производный кэш, порядок, состояние потока;
- `queue` — очередь: пути, хранилище, индекс, настройка проекта, реестр очередей;
- `typedefs` — тип как плагин: объявление, поля, гейты, индекс типов;
- `profile` — профиль типа: универсальный из конфига и загружаемый потомок;
- `validate` — три уровня валидации: схема, поля типа, процедурная проверка;
- `FieldValidator` — отдельный объект проверки `extra` по объявлению типа;
- `gates` — декларативные гейты закрытия и класс `Gates`;
- `checks` — проверка-плагин: объявление, загрузка, контракт входа и выхода;
- `doctor` — диагностика: находки, слияние кодов, линт прозы, покрытие;
- `link` — связь записей указателем, дерево записи, битые указатели и `Linker`;
- `digest` — выгрузка тела и ленты в производный файл для чтения и `Digest`;
- `flow` — поток: шаги как данные, состояние в индексе, цепочка черновиков;
- `brief` — пакет субагенту: бриф, задача, лента, возвратный контракт;
- `report` — печать: строка на объект, положение дел, режимы чтения и `Reporter`;
- `roles` — роли и модели проекта по схеме ROLE-1;
- `tools` — привязки возможностей среды по схеме TOOLS-1;
- `cli` — общий контракт CLI; `queue_cli`, `task_cli`, `check_cli` — составы команд.
"""

