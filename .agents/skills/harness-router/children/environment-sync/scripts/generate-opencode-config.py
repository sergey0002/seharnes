#!/usr/bin/env python3
"""Generate the OpenCode project view from the Cursor canon.

OpenCode (v2) reads the project configuration from `opencode.json` or
`opencode.jsonc` in the project root. It also reads `AGENTS.md` and discovers
`.agents/skills` natively, so only rules and MCP need a generated view:

- rules  `<project>/.opencode/rules/**/*.md` (frontmatter stripped, links rebased)
- index  `<project>/.opencode/rules-index.md` (on-demand rules + glob block)
- MCP    `<project>/opencode.json` -> `mcp.servers` (`type: local|remote`, `disabled`)
- perms  `<project>/.opencode/permissions.fragment.json` (manual merge, like Kilo)

Rule mapping from `.cursor/rules/*.mdc`:

- `alwaysApply: true` -> `instructions` entry, loaded at start
- everything else    -> `.opencode/rules-index.md`, read on demand

OpenCode does not expand `${workspaceFolder}` and `${env:VAR}` in JSON values.
The generator writes absolute paths, keeps secrets in `.cursor/mcp.env` through
`run-with-mcp-env.sh`, and converts header values to OpenCode `{env:NAME}` form.

Usage:
  python3 .agents/skills/harness-router/children/environment-sync/scripts/generate-opencode-config.py --root .
  python3 .agents/skills/harness-router/children/environment-sync/scripts/generate-opencode-config.py --root . --check
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
from pathlib import Path

import rule_model

WRAPPER_NAME = "run-with-mcp-env.sh"
ENV_VAR_RE = re.compile(r"\$\{env:([A-Za-z_][A-Za-z0-9_]*)\}")
OPENCODE_ENV_RE = re.compile(r"\$\{env:([A-Za-z_][A-Za-z0-9_]*)\}")
SCHEMA = "https://opencode.ai/config.json"


def normalize(data: bytes) -> bytes:
    return data.replace(b"\r\n", b"\n").replace(b"\r", b"\n")


def flat_name(relative: Path) -> str:
    parts = relative.with_suffix("").parts
    if len(parts) == 1:
        return parts[0]
    if parts[0] == "mcp" and len(parts) == 2:
        return "mcp-" + parts[1]
    return "-".join(parts)


def render_rule(rule: Path, target: Path) -> str:
    text = rule.read_text(encoding="utf-8")
    body = rule_model.body_without_frontmatter(text)
    body = rule_model.rebase_links(body, rule, target)
    return body.replace("\r\n", "\n").replace("\r", "\n").rstrip() + "\n"


def render_glob_block(rows: list[tuple[str, str, list[str]]]) -> list[str]:
    if not rows:
        return []
    lines = [
        "## Триггеры по пути",
        "",
        "<!-- glob-triggers -->",
        "OpenCode не прикрепляет правило по globs автоматически. Если работа касается пути из таблицы, прочитай правило до действия.",
        "",
        "| Glob | Правило | Файл |",
        "|---|---|---|",
    ]
    for rel, _description, globs in rows:
        name = rel[:-3].replace("/", "-")
        for glob in globs:
            lines.append(f"| `{glob}` | `{name}` | `.opencode/rules/{rel}` |")
    lines.append("")
    return lines


def render_index(rows: list[tuple[str, str, list[str]]],
                 conditional_rows: list[tuple[str, str, list[str]]]) -> str:
    lines = [
        "# Индекс правил по требованию (OpenCode)",
        "",
        "<!-- generated by generate-opencode-config.py; do not edit -->",
        "",
        "Правила ниже не входят в стартовый промпт. Прочитай файл, когда сработал триггер.",
        "OpenCode загружает `instructions` в каждый запрос, поэтому здесь только компактный список.",
        "",
    ]
    lines.extend(render_glob_block(conditional_rows))
    lines.extend([
        "| Правило | Когда читать | Файл |",
        "|---|---|---|",
    ])
    for rel, description, globs in rows:
        name = rel[:-3].replace("/", "-")
        detail = description or "(без описания)"
        if globs:
            detail += " (globs: " + ", ".join(f"`{glob}`" for glob in globs) + ")"
        lines.append(f"| `{name}` | {detail} | `.opencode/rules/{rel}` |")
    return "\n".join(lines) + "\n"


def collect_rules(canon: Path, out: Path) -> tuple[dict[str, str], list[str], list[tuple[str, str, list[str]]],
                                                   list[tuple[str, str, list[str]]]]:
    files: dict[str, str] = {}
    always: list[str] = []
    index_rows: list[tuple[str, str, list[str]]] = []
    conditional: list[tuple[str, str, list[str]]] = []
    for rule in sorted(canon.rglob("*.mdc")):
        relative = rule.relative_to(canon).with_suffix(".md")
        rel_posix = relative.as_posix()
        target = out / relative
        files[rel_posix] = render_rule(rule, target)
        fields = rule_model.rule_frontmatter(rule)
        kind = rule_model.classify(fields)
        if kind == rule_model.ALWAYS:
            always.append(rel_posix)
            continue
        row = (
            rel_posix,
            str(fields.get("description", "")).strip(),
            rule_model.rule_paths(fields),
        )
        index_rows.append(row)
        if kind == rule_model.CONDITIONAL:
            conditional.append(row)
    return files, always, index_rows, conditional


def parse_env_file(path: Path) -> dict[str, str]:
    env: dict[str, str] = {}
    if not path.is_file():
        return env
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export "):].strip()
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if key:
            env[key] = value.strip().strip("'\"")
    return env


def resolve_value(value: str, root: Path, lookup: dict[str, str]) -> str:
    result = value.replace("${workspaceFolder}", str(root))

    def fill(match: re.Match[str]) -> str:
        return lookup.get(match.group(1), os.environ.get(match.group(1), ""))

    return ENV_VAR_RE.sub(fill, result)


def opencode_env(value: str) -> str:
    """Convert Cursor `${env:VAR}` to OpenCode `{env:VAR}` so it resolves at runtime."""
    return OPENCODE_ENV_RE.sub(lambda match: "{env:" + match.group(1) + "}", value)


def render_mcp(root: Path) -> tuple[dict[str, dict], list[dict]]:
    cursor = root / ".cursor"
    canonical = json.loads((cursor / "mcp.json").read_text(encoding="utf-8"))
    global_env = parse_env_file(cursor / "mcp.env")
    lookup = {**os.environ, **global_env}
    default_env = str(cursor / "mcp.env")
    wrapper = str(root / ".tools" / "scripts" / WRAPPER_NAME)
    servers: dict[str, dict] = {}
    permissions: list[dict] = []

    for name, source in sorted(canonical.get("mcpServers", {}).items()):
        server = dict(source)
        disabled = server.get("enabled", True) is False or bool(server.get("disabled"))
        transport = str(server.get("type", "stdio")).lower()
        url = server.get("url") or server.get("serverUrl")
        rendered: dict = {}

        if transport in {"sse", "remote"} or (url and transport not in {"stdio", "local", "http", "streamable-http"}):
            rendered["type"] = "remote"
            rendered["url"] = resolve_value(str(url), root, lookup)
            if server.get("headers") and not disabled:
                rendered["headers"] = {
                    key: opencode_env(str(value)) for key, value in server["headers"].items()
                }
        elif transport in {"http", "streamable-http"} or url:
            rendered["type"] = "remote"
            rendered["url"] = resolve_value(str(url), root, lookup)
            if server.get("headers") and not disabled:
                rendered["headers"] = {
                    key: opencode_env(str(value)) for key, value in server["headers"].items()
                }
        else:
            argv = [str(server["command"]), *[str(part) for part in server.get("args", [])]]
            argv = [resolve_value(part, root, lookup) for part in argv]
            env_file = server.get("envFile")
            if env_file and not any(WRAPPER_NAME in part for part in argv):
                argv = ["bash", wrapper, *argv]
            rendered["type"] = "local"
            rendered["command"] = argv
            environment: dict[str, str] = {}
            for key, value in server.get("env", {}).items():
                if isinstance(value, str) and ENV_VAR_RE.fullmatch(value):
                    continue
                environment[key] = resolve_value(value, root, lookup) if isinstance(value, str) else value
            if env_file:
                resolved_env = resolve_value(str(env_file), root, lookup)
                if resolved_env != default_env:
                    environment["MCP_ENV_FILE"] = resolved_env
            if environment:
                rendered["environment"] = environment
            if server.get("cwd"):
                rendered["cwd"] = resolve_value(str(server["cwd"]), root, lookup)

        if disabled:
            rendered["disabled"] = True
        servers[name] = rendered

        for tool in server.get("alwaysAllow", []):
            permissions.append({"action": f"{name}_{tool}", "resource": "*", "effect": "allow"})
        for tool in server.get("disabledTools", []):
            permissions.append({"action": f"{name}_{tool}", "resource": "*", "effect": "deny"})

    return servers, permissions


def merge_config(previous: object, instructions: list[str], servers: dict[str, dict]) -> dict:
    """Replace managed fields and keep unrelated local settings and servers."""
    result = dict(previous) if isinstance(previous, dict) else {}
    result["$schema"] = SCHEMA
    result["instructions"] = instructions

    previous_mcp = result.get("mcp")
    mcp = dict(previous_mcp) if isinstance(previous_mcp, dict) else {}
    previous_servers = mcp.get("servers")
    merged_servers = dict(previous_servers) if isinstance(previous_servers, dict) else {}
    merged_servers.update(servers)
    mcp["servers"] = merged_servers
    result["mcp"] = mcp
    return result


def check_config(path: Path, instructions: list[str], servers: dict[str, dict]) -> list[str]:
    if not path.is_file():
        return ["missing opencode.json"]
    try:
        actual = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        return [f"unreadable opencode.json: {error}"]
    errors: list[str] = []
    if actual.get("instructions") != instructions:
        errors.append("opencode.json: instructions differ from canon")
    mcp = actual.get("mcp")
    view_servers = mcp.get("servers") if isinstance(mcp, dict) else None
    if not isinstance(view_servers, dict):
        return errors + ["opencode.json: no mcp.servers object"]
    for name, value in sorted(servers.items()):
        if name not in view_servers:
            errors.append(f"opencode.json: missing server {name}")
        elif view_servers[name] != value:
            errors.append(f"opencode.json: stale server {name}")
    return errors


def compare_tree(target: Path, expected: dict[str, str]) -> list[str]:
    errors: list[str] = []
    actual = set()
    if target.is_dir():
        for path in target.rglob("*"):
            if path.is_file() or path.is_symlink():
                actual.add(path.relative_to(target).as_posix())
    for relative in sorted(expected):
        path = target / relative
        if not path.is_file():
            errors.append(f"missing {relative}")
        elif path.is_symlink() or normalize(path.read_bytes()) != expected[relative].encode("utf-8"):
            errors.append(f"stale {relative}")
    errors.extend(f"extra {relative}" for relative in sorted(actual - set(expected)))
    return errors


def clear_tree(target: Path) -> None:
    if target.is_symlink() or target.is_file():
        target.unlink()
    elif target.exists():
        shutil.rmtree(target)


def write_fragment(path: Path, permissions: list[dict]) -> None:
    payload = {
        "_comment": "Generated from .cursor/mcp.json alwaysAllow/disabledTools. "
                    "Merge into the top-level \"permissions\" array of opencode.json "
                    "manually; OpenCode does not load this file. Do not edit.",
        "permissions": permissions,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
                    encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the OpenCode project view")
    parser.add_argument("--root", default=".", help="project root")
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args(argv)

    root = Path(args.root).resolve()
    cursor = root / ".cursor"
    if not (cursor / "mcp.json").is_file():
        print(f"canonical MCP config not found: {cursor / 'mcp.json'}", file=sys.stderr)
        return 2
    if not (cursor / "rules").is_dir():
        print(f"canonical rules directory not found: {cursor / 'rules'}", file=sys.stderr)
        return 2

    out_dir = root / ".opencode"
    rules, always, index_rows, conditional = collect_rules(cursor / "rules", out_dir / "rules")
    index_text = render_index(index_rows, conditional)
    instructions = [f".opencode/rules/{rel}" for rel in sorted(always)]
    if index_rows:
        instructions.append(".opencode/rules-index.md")
    servers, permissions = render_mcp(root)

    if args.check:
        errors: list[str] = []
        errors.extend(compare_tree(out_dir / "rules", rules))
        index_path = out_dir / "rules-index.md"
        if index_rows:
            if not index_path.is_file():
                errors.append("missing .opencode/rules-index.md")
            elif normalize(index_path.read_bytes()) != index_text.encode("utf-8"):
                errors.append("stale .opencode/rules-index.md")
        elif index_path.exists():
            errors.append("extra .opencode/rules-index.md")
        errors.extend(check_config(root / "opencode.json", instructions, servers))
        print(json.dumps({
            "status": "passed" if not errors else "failed",
            "errors": errors,
            "rules": len(rules),
            "instructions": len(instructions),
            "mcp_servers": len(servers),
        }, ensure_ascii=False))
        return 0 if not errors else 1

    target_rules = out_dir / "rules"
    clear_tree(target_rules)
    for relative, content in rules.items():
        destination = target_rules / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8", newline="\n")

    index_path = out_dir / "rules-index.md"
    if index_rows:
        index_path.write_text(index_text, encoding="utf-8", newline="\n")
    elif index_path.exists():
        index_path.unlink()

    fragment = out_dir / "permissions.fragment.json"
    if permissions:
        write_fragment(fragment, permissions)
    elif fragment.exists():
        fragment.unlink()

    config_path = root / "opencode.json"
    previous: object = {}
    if config_path.is_file():
        try:
            previous = json.loads(config_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            previous = {}
    merged = merge_config(previous, instructions, servers)
    config_path.write_text(json.dumps(merged, indent=2, ensure_ascii=False) + "\n",
                           encoding="utf-8", newline="\n")

    print(json.dumps({
        "status": "written",
        "out": str(out_dir),
        "config": str(config_path),
        "rules": len(rules),
        "instructions": len(instructions),
        "mcp_servers": len(servers),
        "permissions": len(permissions),
    }, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
