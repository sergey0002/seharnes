#!/usr/bin/env python3
"""Generate a DeepSeek Harness profile patch from the Cursor canon.

DeepSeek Harness has no "rules" engine and no rules file: workspace guidance is
injected from instruction files (AGENTS.md, CLAUDE.md and configured extras),
skills come from project roots (`.agents/skills` among them), and MCP servers
exist only as explicit `dsh-mcp-client` plugin instances.

This generator bridges the gap:

1. `.dsh/project.patch.yml` - loader patch. Existing rows are patched by id;
   new mcp-client instances are appended through one `insert` list, because a
   patch by an unknown id is rejected by the loader.
2. `DSH-RULES.md` - full always-rule text and on-demand index by default.
   Optional --rules-mode compact emits DSH-BOOTSTRAP.md with mandatory canonical
   reading requirements. Canonical rule text stays in `.cursor/rules`.

Output replacement is atomic per file, not a transaction across the two outputs.
Existing permission bits are preserved; new outputs are private (0600).
Server or model selection with default modes requires an explicit --patch-out;
non-default profiles and rules modes use separate patch filenames.

Pass the patch explicitly:
    dsh --patch .dsh/project.patch.yml web --no-open

Exit codes: 0 success, 1 --check mismatch/unreadable output, 2 argument/input/output error.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import stat
import sys
import tempfile
from pathlib import Path

import rule_model

ENV_VAR_RE = re.compile(r"\$\{env:([A-Za-z_][A-Za-z0-9_]*)\}")
FRONTMATTER_RE = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.S)

NEWLINE = chr(10)
INSTRUCTION_MAX_BYTES = 131072
TOOL_CALL_TIMEOUT_MS = 120000

# DSH-only selection; never changes the shared Cursor server definitions.
MCP_PROFILES = {
    "full": None,
    "research": {"codebase-memory-mcp", "sourcegraph", "serena", "context7", "git"},
    "implementation": {"codebase-memory-mcp", "sourcegraph", "serena", "context7", "git", "mysql"},
    "verification": {"git", "mysql", "playwright", "php-deps-mcp", "phpstan-mcp", "semgrep"},
}


def atomic_write_text(path: Path, content: str) -> None:
    """Replace one resolved file atomically; two calls are not a transaction."""
    target = path.resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    mode = stat.S_IMODE(target.stat().st_mode) if target.exists() else 0o600
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                         dir=target.parent, prefix=f".{target.name}.",
                                         delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
            os.fchmod(stream.fileno(), mode)
        os.replace(temporary, target)
        temporary = None
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def select_servers(servers: dict, profile: str, allow: set[str], exclude: set[str]) -> set[str]:
    """Explicit allow-list overrides a stage; exclusions and canon disable always win."""
    selected = allow or MCP_PROFILES[profile]
    unknown = (selected or set()) - servers.keys()
    if unknown:
        raise ValueError("unknown MCP server names: " + ", ".join(sorted(unknown)))
    return {name for name, server in servers.items()
            if (selected is None or name in selected) and name not in exclude
            and server.get("enabled", True) is not False and not server.get("disabled")}


def emit_compact_bootstrap(rules_dir: Path) -> str:
    """A navigation bootstrap, not a replacement or weakening of canonical rules."""
    lines = [
        "<!-- generated by .agents/skills/harness-router/children/environment-sync/scripts/generate-dsh-config.py; compact bootstrap -->",
        "# DSH bootstrap",
        "",
        "Canonical rules remain mandatory. Before substantive work or response, read",
        "every always rule below not already present in this session context. Read",
        "on-demand rules when their trigger matches. Do not treat this index as a waiver.",
        "Use .dsh/skills/dsh-router/SKILL.md for DSH routing, never as an override of canon.",
        "Read .doc/harnes/doc_rules.md before any .doc content; then architecture/index.md",
        "before code changes. Use canonical skills; do not edit generated IDE mirrors.",
        "No push without explicit request; confirm branch creation and discard. Never",
        "expose secrets. Do not skip canonical plan/audit/test gates to save tokens.",
        "A missing MCP tool is unavailable, not successful: report fallback and limits.",
        "Stage profiles require an explicitly selected startup patch, not a live switch.",
        "",
        "| Rule | Mode | Trigger | File |",
        "|---|---|---|---|",
    ]
    for path in sorted(rules_dir.rglob("*.mdc")):
        name, description, mode, _path = rule_row(path, rules_dir)
        rel = path.relative_to(rules_dir).with_suffix(".mdc").as_posix()
        lines.append(f"| `{name}` | {mode} | {description.replace('|', '/')} | `.cursor/rules/{rel}` |")
    return NEWLINE.join(lines) + NEWLINE


def parse_env_file(path: Path) -> dict[str, str]:
    env: dict[str, str] = {}
    if not path.is_file():
        return env
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export "):].strip()
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip().strip("'\"")
        if key:
            env[key] = value
    return env


def resolve(value: str, root: Path, lookup: dict[str, str]) -> str:
    result = value.replace("${workspaceFolder}", str(root))

    def fill(match: re.Match[str]) -> str:
        return lookup.get(match.group(1), "")

    return ENV_VAR_RE.sub(fill, result)


def server_env(server: dict, root: Path, global_env: dict[str, str]) -> dict[str, str]:
    """Merge envFile and inline env, then expand tokens."""
    merged: dict[str, str] = {}
    env_file = server.get("envFile")
    if env_file:
        merged.update(global_env)
        merged.update(parse_env_file(Path(resolve(str(env_file), root, global_env))))
    for key, value in (server.get("env") or {}).items():
        if isinstance(value, str) and value.startswith("${env:"):
            continue
        merged[str(key)] = str(value)
    lookup = {**global_env, **merged}
    return {key: resolve(value, root, lookup) for key, value in merged.items()}


def mcp_entry(name: str, server: dict, root: Path, global_env: dict[str, str]) -> dict:
    """Translate one Cursor MCP server into a dsh-mcp-client config."""
    lookup = {**global_env}
    server_type = str(server.get("type", "stdio"))
    url = server.get("url") or server.get("serverUrl")

    if server_type in {"http", "sse", "remote"} or (url and server_type not in {"stdio", "local"}):
        config = {
            "transport": "streamable-http",
            "serverName": name,
            "url": resolve(str(url), root, lookup),
            "toolCallTimeoutMs": TOOL_CALL_TIMEOUT_MS,
            "failOnStartupError": False,
        }
        headers = server.get("headers") or {}
        if headers:
            config["headers"] = {str(key): resolve(str(value), root, lookup)
                                 for key, value in headers.items()}
        return config

    command = server.get("command")
    if not command:
        raise ValueError(f"server {name}: no command and no url")
    return {
        "transport": "stdio",
        "serverName": name,
        "command": resolve(str(command), root, lookup),
        "args": [resolve(str(item), root, lookup) for item in server.get("args", [])],
        "env": server_env(server, root, global_env),
        "cwd": str(root),
        "toolCallTimeoutMs": TOOL_CALL_TIMEOUT_MS,
        "failOnStartupError": False,
    }


def yaml_scalar(value) -> str:
    """JSON is valid YAML; keeps quoting deterministic and unicode safe."""
    return json.dumps(value, ensure_ascii=False)


def _render_value(key: str, value, indent: int) -> list[str]:
    """Render an arbitrary config value as nested YAML. Scalars use JSON
    quoting (valid YAML); dicts and lists recurse so plugin configs like
    dsh-llm-pi-ai `providers` stay structured rather than stringified."""
    pad = " " * indent
    if isinstance(value, dict):
        if not value:
            return [f"{pad}{key}:"]
        lines = [f"{pad}{key}:"]
        for sub_key, sub_value in value.items():
            lines.extend(_render_value(sub_key, sub_value, indent + 2))
        return lines
    if isinstance(value, list):
        if not value:
            return [f"{pad}{key}:"]
        lines = [f"{pad}{key}:"]
        for item in value:
            if isinstance(item, (dict, list)):
                lines.extend(_render_list_item(item, indent + 2))
            else:
                lines.append(f"{pad}  - {yaml_scalar(item)}")
        return lines
    return [f"{pad}{key}: {yaml_scalar(value)}"]


def _render_list_item(item, indent: int) -> list[str]:
    """Render one list element that is itself a dict (or list)."""
    pad = " " * indent
    if isinstance(item, dict):
        if not item:
            return [f"{pad}- {{}}"]
        keys = list(item)
        first_key = keys[0]
        first_value = item[first_key]
        if isinstance(first_value, (dict, list)):
            lines = [f"{pad}- {first_key}:"]
            if isinstance(first_value, dict):
                for sub_key, sub_value in first_value.items():
                    lines.extend(_render_value(sub_key, sub_value, indent + 4))
            else:
                for sub in first_value:
                    if isinstance(sub, (dict, list)):
                        lines.extend(_render_list_item(sub, indent + 4))
                    else:
                        lines.append(f"{pad}    - {yaml_scalar(sub)}")
        else:
            lines = [f"{pad}- {first_key}: {yaml_scalar(first_value)}"]
        for key in keys[1:]:
            value = item[key]
            lines.extend(_render_value(key, value, indent + 2))
        return lines
    if isinstance(item, list):
        out: list[str] = []
        for x in item:
            out.extend(_render_list_item(x, indent))
        return out
    return [f"{pad}- {yaml_scalar(item)}"]


def render_entry(entry: dict, indent: int) -> list[str]:
    """Render one loader entry; inserted entries carry an id too."""
    pad = " " * indent
    if entry.get("id"):
        lines = [f"{pad}- id: {entry['id']}", f"{pad}  name: {yaml_scalar(entry['name'])}"]
    else:
        lines = [f"{pad}- name: {yaml_scalar(entry['name'])}"]
    config = entry.get("config")
    if config:
        lines.append(f"{pad}  config:")
        for key, value in config.items():
            lines.extend(_render_value(key, value, indent + 4))
    return lines


def load_overlay(path: Path) -> list[dict]:
    """Read the local model overlay: DSH-only entries the canon cannot supply.

    The overlay is JSON (YAML is a superset, and the generator already emits
    JSON scalars). Missing or unparsable overlay yields no entries; a broken
    overlay is reported by the caller, never silently ignored mid-generation.
    """
    if not path.is_file():
        return []
    data = json.loads(path.read_text(encoding="utf-8"))
    entries: list[dict] = []

    llm = data.get("llm_pi_ai")
    if llm:
        entries.append({
            "id": "llm-pi-ai",
            "name": "@deepseek-ai/dsh-llm-pi-ai",
            "config": {"providers": llm.get("providers", {})},
        })

    if data.get("model_selection"):
        entries.append({
            "id": "subagent-model-selection-settings",
            "name": "@deepseek-ai/dsh-tool-subagent/model-selection-settings",
            "config": data["model_selection"],
        })

    if data.get("subagent"):
        entries.append({
            "id": "tool-subagent",
            "name": "@deepseek-ai/dsh-tool-subagent",
            "config": data["subagent"],
        })

    if data.get("workflow"):
        entries.append({
            "id": "tool-workflow",
            "name": "@deepseek-ai/dsh-tool-workflow",
            "config": data["workflow"],
        })

    return entries


def emit_patch(targeted: list[dict], inserted: list[dict], overlay: list[dict] | None = None) -> str:
    """Targeted entries patch existing ids; new plugins go into one insert list."""
    overlay = overlay or []
    lines = [
        "# Generated by .agents/skills/harness-router/children/environment-sync/scripts/generate-dsh-config.py from .cursor/mcp.json.",
        "# Do not edit: re-run the generator after changing the canon.",
        "# Boot with: dsh --patch .dsh/project.patch.yml web --no-open",
        "",
    ]
    for entry in targeted:
        lines.extend(render_entry(entry, 0))
        lines.append("")
    if inserted or overlay:
        lines.append("# New plugins: MCP clients (canon) + local model routing (overlay).")
        lines.append("- insert:")
        for entry in inserted:
            lines.extend(render_entry(entry, 4))
        for entry in overlay:
            lines.extend(render_entry(entry, 4))
        lines.append("")
    return NEWLINE.join(lines)


MD_LINK_RE = re.compile(r"\]\((\.{1,2}/[^)#]+)(#[^)]*)?\)")


def rebase_links(text: str, source: Path, root: Path) -> str:
    """Rewrite relative markdown links so they resolve from the repo root.

    Rule bodies are inlined into DSH-RULES.md, which sits at the root, while
    the links were written relative to `.cursor/rules/`. Resolving each target
    against the source file and re-relativizing keeps every link clickable.
    """
    def repl(match: re.Match[str]) -> str:
        target, anchor = match.group(1), match.group(2) or ""
        resolved = (source.parent / target).resolve()
        if not resolved.exists():
            return match.group(0)
        try:
            rel = resolved.relative_to(root).as_posix()
        except ValueError:
            return match.group(0)
        if not rel.startswith("."):
            rel = "./" + rel
        return f"]({rel}{anchor})"

    return MD_LINK_RE.sub(repl, text)


def rule_body(path: Path, root: Path | None = None) -> str:
    """Strip YAML frontmatter, return the rule body (title + text)."""
    text = path.read_text(encoding="utf-8")
    match = FRONTMATTER_RE.match(text)
    body = text[match.end():].strip() if match else text.strip()
    if root is not None:
        body = rebase_links(body, path, root)
    return body


def rule_row(path: Path, rules_dir: Path) -> tuple[str, str, str, Path]:
    front = rule_model.rule_frontmatter(path)
    description = str(front.get("description", "")).strip()
    kind = rule_model.classify(front)
    key = path.relative_to(rules_dir).with_suffix("").as_posix().replace("/", "-")
    return key, description or "-", "always" if kind == rule_model.ALWAYS else "on demand", path


def emit_rules_index(rules_dir: Path, root: Path | None = None) -> str:
    """DSH has no always-apply engine, so always rules are INLINED verbatim
    (body without frontmatter) into the instruction file; on-demand rules stay
    a pointer table. Inlining is the only reliable way a rule body reaches the
    model in DSH — a pointer table is never force-read."""
    paths = sorted(rules_dir.rglob("*.mdc"))
    rows = [rule_row(p, rules_dir) for p in paths]
    always_rows = [row for row in rows if row[2] == "always"]
    ondemand_rows = [row for row in rows if row[2] == "on demand"]

    lines = [
        "<!-- generated by .agents/skills/harness-router/children/environment-sync/scripts/generate-dsh-config.py from .cursor/rules -->",
        "",
        "# DeepSeek Harness rules",
        "",
        "DeepSeek Harness has no always-apply rules engine. Always rules are",
        "inlined below and are mandatory for every response. On-demand rules are",
        "listed with their trigger; read the referenced file when the trigger",
        "matches. Canonical source: `.cursor/rules/*.mdc`.",
        "",
    ]

    if always_rows:
        lines.append("## Always rules (inlined, mandatory)")
        lines.append("")
        for name, _description, _mode, path in always_rows:
            body = rule_body(path, root)
            lines.append(f"<!-- rule: {name} (always) -->")
            lines.append(body)
            lines.append("")

    if ondemand_rows:
        lines.append("## On-demand rules (read file when triggered)")
        lines.append("")
        conditional_rows: list[tuple[str, str, str]] = []
        for path in paths:
            front = rule_model.rule_frontmatter(path)
            if rule_model.classify(front) != rule_model.CONDITIONAL:
                continue
            name = path.relative_to(rules_dir).with_suffix("").as_posix().replace("/", "-")
            rel = path.relative_to(rules_dir).with_suffix(".mdc").as_posix()
            for glob in rule_model.rule_paths(front):
                conditional_rows.append((glob, name, rel))
        if conditional_rows:
            lines.append("<!-- glob-triggers -->")
            lines.append("Среда не прикрепляет правило по globs автоматически. Если работа касается пути из таблицы, прочитай правило до действия.")
            lines.append("")
            lines.append("| Glob | Правило | Файл |")
            lines.append("|---|---|---|")
            for glob, name, rel in conditional_rows:
                lines.append(f"| `{glob}` | `{name}` | `.cursor/rules/{rel}` |")
            lines.append("")
        lines.append("| Rule | Trigger / applies to | File |")
        lines.append("|---|---|---|")
        for name, description, _mode, path in ondemand_rows:
            rel = path.relative_to(rules_dir).with_suffix(".mdc").as_posix()
            lines.append(f"| `{name}` | {description} | `.cursor/rules/{rel}` |")
        lines.append("")

    return NEWLINE.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--root", type=Path, default=Path.cwd(), help="project root")
    parser.add_argument("--patch-out", type=Path, default=None, help="default: <root>/.dsh/project.patch.yml")
    parser.add_argument("--rules-out", type=Path, default=None, help="default: <root>/DSH-RULES.md")
    parser.add_argument("--rules-mode", choices=("full", "compact"), default="full",
                        help="full preserves inline rules; compact emits opt-in DSH bootstrap")
    parser.add_argument("--mcp-profile", choices=tuple(MCP_PROFILES), default="full",
                        help="startup server subset; does not switch a live session")
    parser.add_argument("--servers", default="", help="comma separated allow-list overriding profile")
    parser.add_argument("--exclude", default="",
                        help="comma separated names to skip; xdebug is already disabled in canon")
    parser.add_argument("--no-mcp", action="store_true", help="skip MCP entries")
    parser.add_argument("--overlay", type=Path, default=None,
                        help="DSH-only model overlay JSON (default: <root>/.dsh/models.overlay.json)")
    parser.add_argument("--no-llm", action="store_true",
                        help="drop the llm-pi-ai entry from the patch (deepseek-account stays the only route)")
    parser.add_argument("--no-model-selection", action="store_true",
                        help="force subagent modelSelectionSettings=false, keeping the settings row")
    parser.add_argument("--check", action="store_true",
                        help="compare selected outputs without writing or printing secret differences")
    parser.add_argument("--force", action="store_true",
                        help="overwrite a hand-maintained project.patch.yml")
    args = parser.parse_args()

    root = args.root.resolve()
    mcp_path = root / ".cursor" / "mcp.json"
    rules_dir = root / ".cursor" / "rules"
    if not mcp_path.is_file():
        print(f"error: {mcp_path} not found", file=sys.stderr)
        return 2
    if not rules_dir.is_dir():
        print(f"error: {rules_dir} not found", file=sys.stderr)
        return 2

    global_env = parse_env_file(root / ".cursor" / "mcp.env")
    allow = {name.strip() for name in args.servers.split(",") if name.strip()}
    exclude = {name.strip() for name in args.exclude.split(",") if name.strip()}
    servers = json.loads(mcp_path.read_text(encoding="utf-8")).get("mcpServers", {})

    try:
        selected = set() if args.no_mcp else select_servers(servers, args.mcp_profile, allow, exclude)
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    # Non-default modes have independent outputs and cannot overwrite the live default.
    variant = args.rules_mode != "full" or args.mcp_profile != "full"
    if (not variant and args.patch_out is None and
            (args.servers or args.exclude or args.no_mcp or args.overlay is not None
             or args.no_llm or args.no_model_selection)):
        parser.error("server or model selection requires an explicit --patch-out")
    suffix = f"{args.mcp_profile}-{args.rules_mode}"
    patch_out = args.patch_out or (root / ".dsh" / (f"project.{suffix}.patch.yml" if variant else "project.patch.yml"))
    rules_out = args.rules_out or (root / ("DSH-BOOTSTRAP.md" if args.rules_mode == "compact" else "DSH-RULES.md"))
    try:
        aliases = patch_out.resolve() == rules_out.resolve()
        if patch_out.exists() and rules_out.exists():
            aliases = aliases or patch_out.samefile(rules_out)
    except OSError:
        print("error: cannot validate output paths", file=sys.stderr)
        return 2
    if aliases:
        print("error: patch and rules outputs must be distinct files", file=sys.stderr)
        return 2
    # Export paths outside root are useful for parity checks; runtime still uses the default name.
    try:
        instruction_name = rules_out.resolve().relative_to(root).as_posix()
    except ValueError:
        instruction_name = "DSH-BOOTSTRAP.md" if args.rules_mode == "compact" else "DSH-RULES.md"

    targeted: list[dict] = [{
        "id": "agent-instructions",
        "name": "@deepseek-ai/dsh-agent-instructions",
        "config": {
            "maxBytes": INSTRUCTION_MAX_BYTES,
            "instructionFileCandidates": ["AGENTS.md", "CLAUDE.md", instruction_name],
        },
    }]
    inserted: list[dict] = []
    added, skipped = [], []

    if not args.no_mcp:
        for name, server in servers.items():
            if allow and name not in allow:
                skipped.append(f"{name} (not in --servers)")
                continue
            if name in exclude:
                skipped.append(f"{name} (excluded: shares its port with IDE instances)")
                continue
            if server.get("enabled", True) is False or server.get("disabled"):
                skipped.append(f"{name} (disabled in canon)")
                continue
            if name not in selected:
                skipped.append(f"{name} (not in profile)")
                continue
            inserted.append({
                "id": f"mcp-client-{name}",
                "name": "@deepseek-ai/dsh-mcp-client",
                "config": mcp_entry(name, server, root, global_env),
            })
            added.append(name)

    overlay_path = args.overlay or (root / ".dsh" / "models.overlay.json")

    overlay: list[dict] = []
    if overlay_path.is_file():
        try:
            overlay = load_overlay(overlay_path)
        except (ValueError, OSError) as exc:
            print(f"error: overlay {overlay_path} unreadable: {exc}", file=sys.stderr)
            return 2

    # Deliberate environment switches, so the generated patch is not hand-edited
    # after generation. Both were needed on this machine: llm-pi-ai was removed
    # and the standing model-selection settings row failed to activate
    # ("requires a scoped preset Context").
    if args.no_llm:
        overlay = [entry for entry in overlay if entry.get("id") != "llm-pi-ai"]
    if args.no_model_selection:
        for entry in overlay:
            if entry.get("id") == "tool-subagent":
                entry.setdefault("config", {})["modelSelectionSettings"] = False

    patch_text = emit_patch(targeted, inserted, overlay)
    if variant:
        patch_text = patch_text.replace(
            "# Boot with: dsh --patch .dsh/project.patch.yml web --no-open",
            "# Select this patch explicitly at startup; do not stack stage patches.")
    rules_text = (emit_compact_bootstrap(rules_dir) if args.rules_mode == "compact"
                  else emit_rules_index(rules_dir, root))

    # A project may keep its own hand-maintained patch (for example a custom
    # PHP toolchain MCP server). Only rewrite patches this generator owns.
    patch_marker = "# Generated by .agents/skills/harness-router/children/environment-sync/scripts/generate-dsh-config.py"
    hand_maintained = False
    invalid_utf8 = False
    if patch_out.exists() and not args.force:
        try:
            head = patch_out.read_text(encoding="utf-8")[:200]
        except UnicodeDecodeError:
            invalid_utf8 = True
            head = ""
        except OSError:
            head = ""
        if invalid_utf8 and args.check:
            print(json.dumps({"status": "failed", "errors": ["invalid utf8: " + str(patch_out)],
                              "mcp_servers": added, "patch_skipped": True,
                              "runtime_verified": False}, ensure_ascii=False))
            return 1
        hand_maintained = invalid_utf8 or patch_marker not in head

    outputs = [(rules_out, rules_text)]
    if not hand_maintained:
        outputs.insert(0, (patch_out, patch_text))

    if args.check:
        errors = []
        if hand_maintained:
            errors.append(f"hand-maintained patch not checked: {patch_out}")
        for path, expected in outputs:
            try:
                if path.read_text(encoding="utf-8") != expected:
                    errors.append(f"stale: {path}")
            except (OSError, UnicodeError):
                errors.append(f"unreadable: {path}")
        print(json.dumps({"status": "failed" if errors else "passed",
                          "errors": errors, "mcp_servers": added,
                          "patch_skipped": hand_maintained,
                          "runtime_verified": False}, ensure_ascii=False))
        return 1 if errors else 0
    try:
        for path, content in outputs:
            atomic_write_text(path, content)
    except OSError:
        print("error: output replacement failed; outputs are not a transaction; run --check", file=sys.stderr)
        return 2

    print(json.dumps({
        "status": "passed",
        "patch": str(patch_out),
        "patch_skipped": hand_maintained,
        "rules_index": str(rules_out),
        "mcp_servers": added,
        "skipped": skipped,
        "entries": len(targeted) + len(inserted),
        "overlay_entries": len(overlay),
    }, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
