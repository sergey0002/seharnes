#!/usr/bin/env python3
"""Remove generated agent views so the repository stays compact.

Generated views are recreated by sync-agent-views.sh (or harness_transfer
render). Only known managed paths are removed. Qoder's full skill tree is
removed only when it matches the canonical skill tree; discovery wrappers must
carry the generated marker.
"""
from __future__ import annotations

import sys

sys.dont_write_bytecode = True

import argparse
import json
import re
import runpy
import subprocess
from pathlib import Path

from environment_policy import generated_paths, safe_path
import rule_model

BOOT_START = "<!-- BEGIN HARNESS BOOTSTRAP: generated; edit .cursor/rules -->"
BOOT_END = "<!-- END HARNESS BOOTSTRAP -->"
WRAPPER_MARKER = "generated discovery wrapper"


def _validate(root: Path) -> list[str]:
    errors = []
    qoder = root / ".qoder/skills"
    generator = Path(__file__).resolve().parent / "generate-qoder-config.py"
    if qoder.is_dir() and generator.is_file():
        result = subprocess.run([sys.executable, str(generator), "--root", str(root), "--check"],
                                stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE, timeout=180, check=False)
        if result.returncode:
            errors.append("Qoder view does not match the canonical skill tree")
    for relative in (".qwen/skills", ".dsh/skills"):
        view = root / relative
        if not view.is_dir():
            continue
        for entry in sorted(view.iterdir()):
            if not entry.is_dir():
                errors.append(f"unexpected file in {relative}: {entry.name}")
                continue
            if entry.name.startswith("rule-"):
                continue
            files = [item for item in entry.rglob("*") if item.is_file()]
            if len(files) != 1 or files[0].name != "SKILL.md" or files[0].parent != entry:
                errors.append(f"unexpected files in {relative}/{entry.name}")
            elif WRAPPER_MARKER not in files[0].read_text(encoding="utf-8", errors="ignore"):
                errors.append(f"not a generated wrapper: {relative}/{entry.name}")
    return errors


def _agents_state(root: Path) -> tuple[bool, str | None]:
    path = root / "AGENTS.md"
    if path.is_symlink():
        raise ValueError("linked AGENTS.md")
    if not path.is_file():
        return False, None
    text = path.read_text(encoding="utf-8")
    starts = text.count(BOOT_START)
    ends = text.count(BOOT_END)
    if starts != ends or starts > 1:
        raise ValueError("AGENTS.md has incomplete harness bootstrap markers")
    if not starts:
        return False, None
    start, end = text.index(BOOT_START), text.index(BOOT_END)
    if start > end:
        raise ValueError("invalid bootstrap marker order")
    return True, text[:start] + text[end + len(BOOT_END):]


def compact(root: Path, *, apply: bool, force: bool, disabled_only: bool = False) -> dict:
    root = Path(root).absolute()
    if not root.is_dir():
        raise ValueError("root must be an existing directory")
    paths = generated_paths(root, disabled_only=disabled_only)
    for relative in paths:
        safe_path(root, relative)
    errors = [] if force or disabled_only or not apply else _validate(root)
    if errors:
        return {"status": "refused", "errors": errors, "removed": []}
    present, replacements = [], {}
    for relative in paths:
        path = safe_path(root, relative)
        if path.is_symlink():
            if relative != ".kilo/mcp.json":
                errors.append(f"linked generated output: {relative}")
            else:
                present.append(relative)
            continue
        elif not path.exists():
            continue
        if relative == ".dsh/project.patch.yml" and "# Generated by .agents/skills/harness-router/children/environment-sync/scripts/generate-dsh-config.py" not in path.read_text(encoding="utf-8")[:512]:
            continue
        if relative == ".dsh/skills":
            for wrapper in sorted(path.glob("*/SKILL.md")):
                if not wrapper.parent.is_symlink() and not wrapper.is_symlink() and WRAPPER_MARKER in wrapper.read_text(encoding="utf-8"):
                    present.append(wrapper.relative_to(root).as_posix())
            continue
        if relative in {".qoder/settings.json", ".qwen/settings.json", "opencode.json", ".codex/config.toml", ".kilo/kilo.jsonc"}:
            replacement = local_config(path, root, relative)
            if replacement == path.read_text(encoding="utf-8"):
                continue
            if replacement.strip():
                replacements[relative] = replacement
        if path.is_dir() and relative.endswith("/rules"):
            for name, content in rule_outputs(root, relative).items():
                item = path / name
                if item.is_symlink():
                    errors.append(f"linked generated output: {item.relative_to(root)}")
                elif item.is_file():
                    safe_path(root, item.relative_to(root).as_posix())
                    if force or item.read_text(encoding="utf-8") == content:
                        present.append(item.relative_to(root).as_posix())
                    else:
                        errors.append(f"modified generated rule: {item.relative_to(root)}")
            continue
        if path.is_dir() and relative in {".qwen/skills", ".qoder/skills"}:
            skills = generator("qwen")["expected_rules"](root / ".cursor/rules")[1] if relative == ".qwen/skills" else {}
            for item in sorted(path.rglob("*")):
                if not item.is_file() or item.is_symlink():
                    continue
                suffix = item.relative_to(path)
                canonical = root / ".agents/skills" / suffix
                if relative == ".qoder/skills" and canonical.is_file():
                    if force or canonical.read_bytes().replace(b"\r\n", b"\n") == item.read_bytes().replace(b"\r\n", b"\n"):
                        present.append(item.relative_to(root).as_posix())
                    else:
                        errors.append(f"modified Qoder skill: {item.relative_to(root)}")
                elif relative == ".qwen/skills" and item.name == "SKILL.md" and (
                        WRAPPER_MARKER in item.read_text(encoding="utf-8") or
                        suffix.as_posix() in skills and (force or item.read_text(encoding="utf-8") == skills[suffix.as_posix()])):
                    present.append(item.relative_to(root).as_posix())
            continue
        if path.is_dir():
            source = root / ".cursor/scripts"
            for item in sorted(path.rglob("*")):
                original = source / item.relative_to(path)
                if item.is_file() and not item.is_symlink() and original.is_file() and item.read_bytes() == original.read_bytes():
                    present.append(item.relative_to(root).as_posix())
            continue
        if relative.endswith("/mcp.env"):
            source = root / ".cursor/mcp.env"
            if not source.is_file() or path.read_bytes() != source.read_bytes():
                continue
        present.append(relative)
    if errors:
        return {"status": "refused", "errors": errors, "removed": [], "present": present}
    agents_pending, agents_content = (False, None) if disabled_only else _agents_state(root)
    if agents_pending:
        present.append("AGENTS.md#bootstrap")
    for relative in present:
        if relative != "AGENTS.md#bootstrap":
            safe_path(root, relative)
    if apply:
        if agents_pending:
            (root / "AGENTS.md").write_text(agents_content, encoding="utf-8", newline="\n")
        for relative in present:
            if relative == "AGENTS.md#bootstrap":
                continue
            path = safe_path(root, relative)
            if relative in replacements:
                path.write_text(replacements[relative], encoding="utf-8")
            else:
                path.unlink()
                for parent in path.parents:
                    if parent == root or parent.relative_to(root).parts[0] in {".agents", ".doc"} and len(parent.relative_to(root).parts) == 1:
                        break
                    try:
                        parent.rmdir()
                    except OSError:
                        break
    status = "compacted" if apply or not present else "pending"
    return {"status": status, "present": present, "removed": present if apply else []}


def generator(env: str) -> dict:
    filename = "generate-antigravity-rules.py" if env == "agents" else f"generate-{env}-config.py"
    return runpy.run_path(str(Path(__file__).with_name(filename)))


def rule_outputs(root: Path, relative: str) -> dict[str, str]:
    source = root / ".cursor/rules"
    env = relative.split("/", 1)[0][1:]
    if env == "qoder":
        return generator(env)["expected_rules"](source)
    if env == "qwen":
        return generator(env)["expected_rules"](source)[0]
    if env == "agents":
        adapter = generator(env)
        return {adapter["flat_name"](p.relative_to(source)): adapter["render"](p, p.relative_to(source), root / relative / adapter["flat_name"](p.relative_to(source)))
                for p in sorted(source.rglob("*.mdc"))}
    return {p.relative_to(source).with_suffix(".md").as_posix(): rule_model.rebase_links(
                rule_model.body_without_frontmatter(p.read_text(encoding="utf-8")), p,
                root / relative / p.relative_to(source).with_suffix(".md")).rstrip() + "\n"
            for p in sorted(source.rglob("*.mdc"))}


def local_config(path: Path, root: Path, relative: str) -> str:
    import tomllib
    original = path.read_text(encoding="utf-8")
    canon = root / ".cursor/mcp.json"
    if not canon.is_file():
        return original
    names = set(json.loads(canon.read_text(encoding="utf-8"))["mcpServers"])
    if relative == ".codex/config.toml":
        servers = tomllib.loads(original).get("mcp_servers", {})
        if not servers:
            return original
        if set(servers) - names or any({"tools", "default_tools_approval_mode"} & set(entry) for entry in servers.values()):
            raise ValueError("Codex MCP contains local settings; review before cleanup")
        adapter = runpy.run_path(str(Path(__file__).with_name("generate-codex-mcp.py")))
        expected = tomllib.loads(adapter["generate"](original, json.loads(canon.read_text(encoding="utf-8")), root))
        if any(entry != expected.get("mcp_servers", {}).get(name) for name, entry in servers.items()):
            raise ValueError("Codex MCP contains local changes or drift; review before cleanup")
        return adapter["remove_mcp"](original)
    if relative == ".kilo/kilo.jsonc" and not original.startswith("// Generated from .cursor/mcp.json by "):
        return original
    source = re.sub(r"(?m)^\s*//[^\n]*", "", original) if relative == ".kilo/kilo.jsonc" else original
    data = json.loads(source)
    before = json.loads(source)
    if relative in {"opencode.json", ".kilo/kilo.jsonc"}:
        instructions = data.get("instructions", [])
        prefix = ".opencode" if relative == "opencode.json" else ".kilo"
        remaining = [item for item in instructions if not (item.startswith(f"{prefix}/rules/") or item == f"{prefix}/rules-index.md")]
        if remaining != instructions:
            if remaining:
                data["instructions"] = remaining
            else:
                data.pop("instructions", None)
        mcp = data.get("mcp", {})
        servers = mcp.get("servers", {}) if relative == "opencode.json" else mcp
    else:
        mcp = data.get("mcp", {})
        servers = data.get("mcpServers", {})
        for key in ("excluded", "enabledProjectMcpServers"):
            if key in mcp:
                mcp[key] = [name for name in mcp[key] if name not in names]
                if not mcp[key]:
                    del mcp[key]
    managed = names & servers.keys()
    if managed and relative != ".kilo/kilo.jsonc":
        env = {"opencode.json": "opencode", ".qwen/settings.json": "qwen", ".qoder/settings.json": "qoder"}[relative]
        rendered = generator(env)["render_mcp"](root)
        expected = rendered[0] if env == "opencode" else rendered["mcpServers"]
        if any(servers[name] != expected.get(name) for name in managed):
            raise ValueError(f"{relative}: canonical MCP entries contain local changes or drift; review before cleanup")
    for name in managed:
        del servers[name]
    if relative == "opencode.json" and not servers:
        mcp.pop("servers", None)
    if relative not in {"opencode.json", ".kilo/kilo.jsonc"} and not servers:
        data.pop("mcpServers", None)
    if not mcp:
        data.pop("mcp", None)
    if data == before:
        return original
    if set(data) <= {"$schema"}:
        return ""
    return json.dumps(data, ensure_ascii=False, indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--check", action="store_true", help="report generated paths without removing")
    action.add_argument("--apply", action="store_true", help="remove generated paths")
    parser.add_argument("--force", action="store_true", help="skip content validation")
    args = parser.parse_args(argv)
    try:
        report = compact(args.root, apply=args.apply, force=args.force)
    except (OSError, ValueError) as error:
        print(json.dumps({"status": "failed", "errors": [str(error)]}, ensure_ascii=False))
        return 2
    print(json.dumps(report, ensure_ascii=False))
    if report["status"] == "refused":
        return 2
    if args.check and report["present"]:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
