#!/usr/bin/env python3
"""Render machine policy tables into authored Markdown between fixed markers.

`--check` reports drift and `--write` replaces only the marked blocks. Authored
prose outside the markers is never changed.
"""
from __future__ import annotations

import sys

sys.dont_write_bytecode = True

import argparse
import json
import os
import re
import stat
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from canon_paths import load_preliminary_policy_bundle, read_policy

DOCS = {
    "skill_format": ".doc/harnes/skill-format.md",
    "component_docs": ".doc/harnes/component-docs.md",
}
PARAMETER_KEYS = {"severity", "enabled", "scope"}


def _render_value(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, list):
        return ", ".join(f"`{item}`" for item in value)
    return f"`{value}`"


def render_block(policy_id: str, rules: dict) -> str:
    lines = [f"<!-- BEGIN POLICY {policy_id} (generated by render_policy_docs.py; do not edit) -->",
             "| Rule | Severity | Enabled | Scope | Parameters |", "|---|---|---|---|---|"]
    for rule_id in sorted(rules):
        rule = rules[rule_id]
        parameters = "; ".join(f"{key}={_render_value(rule[key])}"
                               for key in sorted(rule) if key not in PARAMETER_KEYS)
        lines.append(f"| `{rule_id}` | {rule['severity']} | {str(rule['enabled']).lower()} | "
                     f"{rule['scope']} | {parameters} |")
    lines.append(f"<!-- END POLICY {policy_id} -->")
    return "\n".join(lines)


def _pattern(policy_id: str) -> re.Pattern:
    return re.compile(rf"<!-- BEGIN POLICY {policy_id} \(generated by render_policy_docs\.py; do not edit\) -->"
                      rf".*?<!-- END POLICY {policy_id} -->", re.DOTALL)


def _safe_path(root: Path, relative: str) -> Path:
    current = root
    for part in relative.split("/"):
        current = current / part
        try:
            info = current.lstat()
        except OSError as error:
            raise ValueError("policy document is missing") from error
        if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & getattr(
                stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400):
            raise ValueError("policy document must not have links")
    if not current.is_file():
        raise ValueError("policy document is not a regular file")
    return current


def _write(path: Path, text: str) -> None:
    temporary = path.with_name("." + path.name + ".policy.tmp")
    mode = stat.S_IMODE(path.stat().st_mode)
    with open(temporary, "w", encoding="utf-8", newline="") as stream:
        stream.write(text)
        stream.flush()
        os.fsync(stream.fileno())
    os.chmod(temporary, mode)
    os.replace(temporary, path)


def check_or_write(root: Path, write: bool) -> dict:
    if not any((root / relative).exists() for relative in DOCS.values()):
        return {"status": "not_applicable", "reason": "policy documents are absent",
                "checked": [], "drifted": [], "written": False}
    bundle = load_preliminary_policy_bundle(root)
    drifted, checked = [], []
    for policy_id, relative in DOCS.items():
        path = _safe_path(root, relative)
        text = path.read_text(encoding="utf-8")
        pattern = _pattern(policy_id)
        matches = list(pattern.finditer(text))
        if len(matches) != 1:
            raise ValueError(f"markers_missing: {relative} needs exactly one generated block")
        rendered = render_block(policy_id, bundle["policies"][policy_id]["rules"])
        checked.append(relative)
        if matches[0].group(0) == rendered:
            continue
        drifted.append(relative)
        if write:
            _write(path, text[:matches[0].start()] + rendered + text[matches[0].end():])
    return {"status": "drift" if drifted and not write else "ok", "checked": checked,
            "drifted": drifted, "written": bool(write and drifted)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[6])
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--check", action="store_true", help="fail when a block differs")
    action.add_argument("--write", action="store_true", help="replace marked blocks")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    try:
        report = check_or_write(args.root.absolute(), args.write and not args.check)
    except (OSError, ValueError) as error:
        print(json.dumps({"status": "failed", "reason": str(error)}, ensure_ascii=False))
        return 2
    print(json.dumps(report, ensure_ascii=False, sort_keys=True))
    return 0 if report["status"] in ("ok", "not_applicable") else 1


if __name__ == "__main__":
    raise SystemExit(main())
