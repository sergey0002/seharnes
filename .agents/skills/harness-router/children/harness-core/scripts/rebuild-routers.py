#!/usr/bin/env python3
"""Rebuild router SKILL.md files from the skill tree.

A router is a directory whose name ends with `-router`. Routers contain only
routing. Children are read from `skill.json.children`; triggers are read from
`skill.json.triggers` or derived from `description`. Every router lists all
descendants with full project paths, so a client can read the exact file without
resolving a path relative to the router directory.

Usage:
  python3 rebuild-routers.py --root . --check
  python3 rebuild-routers.py --root . --write
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

BEGIN = "<!-- BEGIN ROUTER: generated by rebuild-routers.py -->"
END = "<!-- END ROUTER -->"

ROUTER_DESCRIPTIONS = {
    "harness-router": "Главный маршрутизатор харнеса: синхронизация сред, перенос kit, настройка проекта, аудит MCP, карта харнеса, улучшение харнеса.",
    "task-router": "Главный маршрутизатор задач: постановка задачи, сбор требований и формулировка задачи, переход к задаче, diff, заведение, code review, git-task-blame, Jira, Kaiten, аналитика, тестирование, отчеты, документация задачи.",
    "testing-router": "Маршрутизатор тестирования: тесты задачи, подготовка тестов, браузерная проверка.",
    "reporting-router": "Маршрутизатор отчетов: короткий отчет в трекер и HTML-отчет об изменениях.",
    "documentation-router": "Маршрутизатор документации: карта проекта, сверка документации с кодом, документация задачи.",
}
FALLBACK = {"harness-core", "task-core"}


def split_frontmatter(text: str) -> tuple[dict, str]:
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end < 0:
        return {}, text
    block = text[3:end]
    body = text[end + 4:]
    if body.startswith("\n"):
        body = body[1:]
    data: dict[str, str] = {}
    lines = block.splitlines()
    index = 0
    while index < len(lines):
        match = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", lines[index])
        if not match:
            index += 1
            continue
        key, value = match.group(1), match.group(2).strip()
        if value in {">", ">-", "|", "|-"}:
            parts = []
            index += 1
            while index < len(lines) and (not lines[index] or lines[index].startswith((" ", "\t"))):
                parts.append(lines[index].strip())
                index += 1
            value = " ".join(part for part in parts if part)
        data[key] = value.strip("\"'")
        index += 1
    return data, body


def load_skill(path: Path) -> tuple[dict, dict, str]:
    data = json.loads((path / "skill.json").read_text(encoding="utf-8"))
    front, body = split_frontmatter((path / "SKILL.md").read_text(encoding="utf-8"))
    return data, front, body


def children_of(path: Path, data: dict) -> list[Path]:
    return [p for p in ((path / c).resolve() for c in data.get("children", [])) if p.is_dir()]


def collect_triggers(path: Path, stack: set[Path] | None = None) -> list[str]:
    stack = stack or set()
    if path in stack:
        raise RuntimeError(f"cycle: {path}")
    stack.add(path)
    data, front, _ = load_skill(path)
    raw = data.get("triggers")
    if isinstance(raw, list):
        result = [str(x).strip() for x in raw if str(x).strip()]
    else:
        text = str(front.get("description", "")).split("Применять по запросам", 1)[0]
        text = text.split("Use when", 1)[0]
        result = [part.strip(" .") for part in re.split(r"[,;|]", text) if part.strip(" .")]
    result = [item for item in result if item and item not in {">-", ">"}]
    for child in children_of(path, data):
        result.extend(collect_triggers(child, stack))
    stack.remove(path)
    return result


def first_sentence(text: str) -> str:
    text = str(text or "").strip()
    if not text:
        return "нет описания"
    parts = re.split(r"(?<=[.!?])\s+", text)
    return parts[0].strip()


def all_descendants(path: Path, data: dict, depth: int = 1) -> list[tuple[Path, int]]:
    result = []
    for child in children_of(path, data):
        result.append((child, depth))
        child_data, _, _ = load_skill(child)
        result.extend(all_descendants(child, child_data, depth + 1))
    return result


def compact_triggers(path: Path) -> str:
    data, front, _ = load_skill(path)
    raw = data.get("triggers")
    if isinstance(raw, list):
        values = [str(x).strip() for x in raw if str(x).strip()]
    else:
        text = str(front.get("description", ""))
        for marker in ("Применять по запросам", "Use when"):
            if marker in text:
                text = text.split(marker, 1)[1].lstrip(" :")
                break
        values = [part.strip(" .") for part in re.split(r"[,;|]", text) if part.strip(" .")]
    values = [value for value in values if value and len(value) <= 70]
    return ", ".join(dict.fromkeys(values)) or "нет"


def table_for(path: Path, data: dict, skills_root: Path) -> str:
    rows = ["| Скил | Файл | Ур. | Когда вызывать: ответственность и триггеры |", "|---|---|---|---|"]
    items = all_descendants(path, data)
    items.sort(key=lambda item: (item[0].name in FALLBACK, item[0].name.lower()))
    for child, depth in items:
        child_data, front, _ = load_skill(child)
        rel = ".agents/skills/" + child.relative_to(skills_root).as_posix() + "/SKILL.md"
        resp = first_sentence(front.get("description", ""))
        triggers = compact_triggers(child)
        extra = [item.strip() for item in triggers.split(",") if item.strip() and item.strip().lower() not in resp.lower()]
        detail = resp if not extra else resp + "; триггеры: " + ", ".join(dict.fromkeys(extra))
        if child.name in FALLBACK:
            detail = "**Fallback/ядро.** " + detail
        rows.append(f"| `{child.name}` | `{rel}` | {depth} | {detail} |")
    return BEGIN + "\n" + "\n".join(rows) + "\n" + END


def render_router(path: Path, data: dict, front: dict, skills_root: Path) -> str:
    name = str(front.get("name", path.name))
    children = [child.name for child, _ in all_descendants(path, data)]
    base = ROUTER_DESCRIPTIONS.get(name, "Маршрутизирует запросы к дочерним скилам.")
    description = base + " Дочерние: " + ", ".join(children) + "."
    table = table_for(path, data, skills_root)
    body = f'''# {name}

Роутер {name}. Содержит только маршрутизацию. Полезная нагрузка лежит в дочерних скилах.

## Контекст путей

Все пути в таблице указаны от корня проекта, например
`.agents/skills/harness-router/children/mcp-audit/SKILL.md`.
Читай выбранный файл инструментом чтения файлов (`Read` / `view_file` / аналог)
именно по полному пути из таблицы.

## Алгоритм выполнения

1. Выбери ровно один наиболее точный дочерний скил по таблице.
2. Сначала проверяй узкие скилы. `harness-core` и `task-core` используй только как fallback для комплексного запроса, который не покрыт узким скилом.
3. Прочитай выбранный файл `SKILL.md` инструментом чтения по полному пути из таблицы.
4. Выполни шаги из прочитанного файла. Не отвечай по теме, пока файл не прочитан.
5. Не читай несколько дочерних скилов одновременно без необходимости.

## Маршрутизация

{table}

## Выход

- Прочитанный файл выбранного дочернего скила и результат выполнения его шагов.

## Ограничения

- Роутер не содержит скриптов, данных и содержательных инструкций.
- Запрещено отвечать по теме харнеса, не прочитав выбранный файл.
- Запрещено массовое чтение дочерних скилов «на всякий случай».
'''
    return f"---\nname: {name}\ndescription: {description}\n---\n\n{body}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=".")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)
    root = (Path(args.root) / ".agents" / "skills").resolve()
    routers = sorted(p for p in root.rglob("*") if p.is_dir() and p.name.endswith("-router"))
    errors, changed = [], []
    for router in routers:
        try:
            data, front, _ = load_skill(router)
            expected = render_router(router, data, front, root)
        except Exception as error:
            errors.append(f"{router}: {error}")
            continue
        current = (router / "SKILL.md").read_text(encoding="utf-8")
        if expected != current:
            changed.append(str(router.relative_to(root)))
            if args.write:
                (router / "SKILL.md").write_text(expected, encoding="utf-8")
    status = "passed" if not errors and (not args.check or not changed) else "failed"
    payload = {"routers": len(routers), "changed": changed, "errors": errors, "status": status}
    if args.json:
        print(json.dumps(payload, ensure_ascii=False, indent=2))
    else:
        print(f"routers={len(routers)} changed={len(changed)} errors={len(errors)}")
        for item in changed:
            print("changed:", item)
        for item in errors:
            print("error:", item)
    return 0 if status == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
